"""Profile the original UCI workbook without changing or cleaning its records."""
from pathlib import Path
import hashlib
import json
import platform
import pandas as pd
import openpyxl

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/raw/online_retail_II.xlsx'

def main():
    workbook = pd.ExcelFile(SOURCE, engine='openpyxl')
    frames = []
    sheets = {}
    expected = ['Invoice', 'StockCode', 'Description', 'Quantity', 'InvoiceDate', 'Price', 'Customer ID', 'Country']
    for name in workbook.sheet_names:
        print(f'Reading {name}...', flush=True)
        frame = pd.read_excel(workbook, sheet_name=name)
        if list(frame.columns) != expected:
            raise ValueError(f'Unexpected columns in {name}: {list(frame.columns)}')
        sheets[name] = {'rows': len(frame), 'columns': list(frame.columns)}
        frames.append(frame)
    data = pd.concat(frames, ignore_index=True)
    dates = pd.to_datetime(data['InvoiceDate'], errors='coerce')
    quantity = pd.to_numeric(data['Quantity'], errors='coerce')
    price = pd.to_numeric(data['Price'], errors='coerce')
    cancellation = data['Invoice'].astype('string').str.upper().str.startswith('C', na=False)
    report = {
        'source_url': 'https://archive.ics.uci.edu/dataset/502/online+retail+ii',
        'download_date': '2026-10-18',
        'sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'file_size_bytes': SOURCE.stat().st_size,
        'versions': {'python': platform.python_version(), 'pandas': pd.__version__, 'openpyxl': openpyxl.__version__},
        'sheets': sheets, 'total_rows': len(data), 'original_columns': len(data.columns),
        'date_min': str(dates.min()), 'date_max': str(dates.max()),
        'calendar_months_present': int(dates.dt.to_period('M').nunique()),
        'missing_by_column': {k: int(v) for k, v in data.isna().sum().items()},
        'duplicate_rows_beyond_first': int(data.duplicated().sum()),
        'cancellation_lines': int(cancellation.sum()),
        'negative_quantity_lines': int((quantity < 0).sum()),
        'zero_quantity_lines': int((quantity == 0).sum()),
        'negative_price_lines': int((price < 0).sum()),
        'zero_price_lines': int((price == 0).sum()),
        'invalid_dates': int(dates.isna().sum()),
        'nonnumeric_quantity': int(quantity.isna().sum()),
        'nonnumeric_price': int(price.isna().sum()),
        'categorical_unique_nonmissing': {c: int(data[c].nunique()) for c in ['StockCode', 'Country', 'Customer ID']},
        'quantity_range': [float(quantity.min()), float(quantity.max())],
        'price_range': [float(price.min()), float(price.max())],
        'notes': ['Issue counts overlap and must not be added.', 'Duplicate rows are candidates for investigation, not proof of error.', 'No rows removed; no hypothesis tested; no model fitted.']
    }
    output = ROOT / 'reports'
    output.mkdir(exist_ok=True)
    (output / 'dataset-profile.json').write_text(json.dumps(report, indent=2) + '\n')
    lines = ['# Dataset quality profile', '', 'Generated by `src/check_dataset.py` from the unmodified workbook.', '', '| Check | Observed result |', '|---|---|']
    for key, value in report.items():
        lines.append(f'| {key} | {json.dumps(value, ensure_ascii=False)} |')
    (output / 'dataset-quality.md').write_text('\n'.join(lines) + '\n')
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
